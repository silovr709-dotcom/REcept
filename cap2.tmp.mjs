import chromium from '@sparticuz/chromium';
import puppeteer from 'puppeteer-core';
const b = await puppeteer.launch({ args:[...chromium.args,'--no-sandbox'], executablePath: await chromium.executablePath(), headless:true });
const p = await b.newPage(); await p.setViewport({width:390,height:844});
await p.goto('http://127.0.0.1:3000/',{waitUntil:'networkidle0',timeout:180000});
await new Promise(r=>setTimeout(r,2500));
const burger = await p.$('button[aria-controls="mobile-menu"]') || (await p.$$('header button')).pop();
await burger.click(); await new Promise(r=>setTimeout(r,1000));
await p.screenshot({path:'/tmp/c-menu.png'}); console.log('ok menu');
await b.close();

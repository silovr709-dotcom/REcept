import type { Metadata } from 'next';
import { PageHero } from '@/components/PageHero';
import { Section } from '@/components/ui/Section';
import { getSiteView } from '@/lib/content/view';

export const metadata: Metadata = {
  title: 'Политика обработки персональных данных',
  description:
    'Как мебельное ателье «РЕцепт» обрабатывает персональные данные, оставленные через формы на сайте.',
  alternates: { canonical: '/politika-konfidencialnosti' },
  robots: { index: false, follow: true },
};

function buildBlocks(site: { legalName: string; url: string }): { h: string; p: string[] }[] {
  return [
  {
    h: '1. Общие положения',
    p: [
      `Настоящая политика описывает, как ${site.legalName} (далее — «мы») обрабатывает персональные данные посетителей сайта ${site.url}.`,
      'Оставляя данные в формах на сайте, вы подтверждаете согласие на их обработку на условиях, описанных ниже.',
    ],
  },
  {
    h: '2. Какие данные мы собираем',
    p: [
      'Через формы на сайте мы получаем только те данные, которые вы указали сами: имя, способ связи (телефон, ник в мессенджере или адрес электронной почты), текст сообщения и, если вы их приложили, файлы с фотографиями или планировкой помещения.',
      'Дополнительно сохраняется техническая информация о том, с какой страницы отправлена заявка — это нужно нам, чтобы понимать контекст обращения.',
    ],
  },
  {
    h: '3. Зачем мы их используем',
    p: [
      'Единственная цель обработки — связаться с вами по вашему обращению, обсудить задачу, подготовить проект и расчёт, а также выполнить работы, если мы договоримся о сотрудничестве.',
      'Мы не используем ваши данные для рассылок, не продаём и не передаём их третьим лицам для рекламных целей.',
    ],
  },
  {
    h: '4. Кому передаются данные',
    p: [
      'Данные доступны только владельцам ателье. Передача третьим лицам возможна исключительно в объёме, необходимом для выполнения вашего заказа (например, служба доставки), или в случаях, предусмотренных законодательством Российской Федерации.',
    ],
  },
  {
    h: '5. Сколько мы их храним',
    p: [
      'Мы храним данные ровно столько, сколько необходимо для обработки обращения и исполнения обязательств по заказу, включая гарантийный срок. По вашему запросу мы удалим данные раньше.',
    ],
  },
  {
    h: '6. Ваши права',
    p: [
      'Вы вправе в любой момент запросить сведения об обработке ваших данных, потребовать их уточнения, блокирования или удаления, а также отозвать согласие на обработку. Для этого достаточно связаться с нами любым удобным способом.',
    ],
  },
  {
    h: '7. Файлы cookie и аналитика',
    p: [
      'Сайт использует только технически необходимые механизмы хранения данных в браузере — например, отметку о том, что вы уже посещали сайт, чтобы не показывать заставку загрузки повторно в полном виде. Эти данные не позволяют вас идентифицировать.',
    ],
  },
  ];
}

export default async function PrivacyPage() {
  const site = await getSiteView();
  const blocks = buildBlocks(site);
  const activeContacts = site.contacts;

  return (
    <>
      <PageHero
        eyebrow="Документы"
        title="Политика обработки персональных данных"
        breadcrumbs={[{ name: 'Политика обработки персональных данных' }]}
      />

      <Section tone="bone" className="pt-0! lg:pt-0!">
        <div className="container-page">
          <div className="container-text rounded-lg border border-line bg-cream p-7 sm:p-12">
            {blocks.map((b) => (
              <section key={b.h} className="mt-10 first:mt-0">
                <h2 className="font-display text-h3 text-ink">{b.h}</h2>
                {b.p.map((text) => (
                  <p key={text} className="mt-4 text-stone">
                    {text}
                  </p>
                ))}
              </section>
            ))}

            <section className="mt-10">
              <h2 className="font-display text-h3 text-ink">8. Контакты</h2>
              {activeContacts.length > 0 ? (
                <p className="mt-4 text-stone">
                  По любым вопросам, связанным с обработкой персональных данных,
                  свяжитесь с нами:{' '}
                  {activeContacts.map((c, i) => (
                    <span key={c.id}>
                      {i > 0 ? ', ' : ''}
                      <a
                        href={c.href}
                        className="text-ink underline decoration-brass/50 underline-offset-4"
                      >
                        {c.value}
                      </a>
                    </span>
                  ))}
                  .
                </p>
              ) : (
                <p className="mt-4 text-stone">
                  По любым вопросам, связанным с обработкой персональных данных,
                  напишите нам через форму на странице{' '}
                  <a
                    href="/kontakty"
                    className="text-ink underline decoration-brass/50 underline-offset-4"
                  >
                    «Контакты»
                  </a>
                  .
                </p>
              )}
            </section>
          </div>
        </div>
      </Section>
    </>
  );
}

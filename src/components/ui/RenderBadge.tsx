/**
 * ПЛАШКА ТИПА ИЗОБРАЖЕНИЯ
 * =======================
 *
 * Портфолио на сайте — фотографии выполненных кухонь. Иллюстрации
 * проектных деталей и интерьеров помечаются «Визуализация», постановочные
 * портреты владельцев — «Постановочный кадр».
 *
 * Подпись рядом с разделом легко пропустить, а изображение принимают
 * за документальное свидетельство. Поэтому тип кадра указан прямо
 * поверх изображения. Компонент принимает свой label для разных типов.
 *
 * Правило: любое недокументальное изображение должно быть подписано.
 */
export function RenderBadge({
  className = '',
  label = 'Визуализация',
}: {
  className?: string;
  label?: string;
}) {
  return (
    <span
      className={`pointer-events-none absolute bottom-3 left-3 z-10 bg-ink/70 px-2.5 py-1 text-caption font-semibold uppercase tracking-[0.16em] text-cream/90 backdrop-blur-[2px] ${className}`}
    >
      {label}
    </span>
  );
}

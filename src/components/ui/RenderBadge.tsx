/**
 * ПЛАШКА «ВИЗУАЛИЗАЦИЯ»
 * =====================
 *
 * Портфолио на сайте — настоящие фотографии наших кухонь. Но в разделах
 * «другие помещения» и «фрезеровки» часть изображений — проектные
 * визуализации: своей съёмки этих объектов у нас пока нет.
 *
 * Раньше об этом было сказано только в тексте раздела. Человек текст
 * пропускает, а картинку видит — и может решить, что ему показали
 * фотографию. Плашка снимает вопрос прямо на изображении.
 *
 * Правило: любое изображение, которое не является фотографией объекта,
 * обязано нести эту плашку.
 */
export function RenderBadge({
  className = '',
  label = 'Визуализация',
}: {
  className?: string;
  label?: string;
}) {
  return (
    <span
      className={`pointer-events-none absolute bottom-3 left-3 z-10 bg-ink/70 px-2.5 py-1 text-[0.625rem] font-semibold uppercase tracking-[0.16em] text-cream/90 backdrop-blur-[2px] ${className}`}
    >
      {label}
    </span>
  );
}

/**
 * ФРЕЗЕРОВКИ ФАСАДОВ — ЕДИНЫЙ СПРАВОЧНИК
 * ======================================
 * Фрезеровка — рисунок, который фреза оставляет на плите МДФ. Он задаёт
 * характер кухни сильнее, чем цвет: одна и та же белая кухня с «Аркой»
 * и со «Стрит» выглядит как мебель из разных эпох.
 *
 * Данные собраны из каталога фабрики, которая изготавливает нам фасады,
 * и из рабочего калькулятора ателье: название, категория сложности,
 * в каком покрытии рисунок вообще делается, толщина плиты и допустимые
 * габариты глухого фасада.
 *
 * Чего здесь нет и не будет: рублей и названия фабрики. Категория — это
 * сложность рисунка, а не цена; прайс поставщика публиковать мы не вправе.
 *
 * Выкраски (`/images/millings/<slug>.webp`) — изображения из каталога
 * фабрики, размещены с ведома владельцев ателье. Они маленькие, 440×362,
 * поэтому показываются только в размер карточки.
 */

